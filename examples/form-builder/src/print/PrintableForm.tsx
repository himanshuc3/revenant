import type { PrintModel } from './model';

const HEADING_TAG = { xl: 'h2', lg: 'h3', md: 'h4', sm: 'h5', xs: 'h6' } as const;

/**
 * The exported document. Plain semantic HTML with no UI-library dependency, so
 * it renders identically inside the print iframe and in tests.
 */
export function PrintableForm({ model }: { model: PrintModel }) {
  return (
    <article className="doc">
      <header className="doc-header">
        <h1 className="doc-title">{model.title}</h1>
        <p className="doc-meta">Submitted {model.submittedAt}</p>
        {model.description && <p className="doc-description">{model.description}</p>}
      </header>

      <section className="doc-body">
        {model.items.length === 0 && <p className="doc-empty">This form has no visible fields.</p>}
        {model.items.map((item, i) => {
          if (item.kind === 'header') {
            const Tag = HEADING_TAG[item.size];
            return (
              <Tag key={i} className={`sec sec-${item.size}`}>
                {item.label}
              </Tag>
            );
          }
          return (
            <div key={i} className="row">
              <div className="row-label">{item.label}</div>
              <div className={item.empty ? 'row-value row-value-empty' : 'row-value'}>
                {item.lines.map((line, j) => (
                  <div key={j}>{line}</div>
                ))}
                {item.note && <div className="row-note">{item.note}</div>}
              </div>
            </div>
          );
        })}
      </section>

      <footer className="doc-footer">Generated by Form Builder</footer>
    </article>
  );
}
